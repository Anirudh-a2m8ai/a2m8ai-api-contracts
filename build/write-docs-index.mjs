#!/usr/bin/env node
/**
 * Writes docs/index.html, a tiny static page linking each spec's generated
 * HTML doc. Discovers the spec list from redocly.yaml's `apis:` map, same as
 * build/pull-spec.mjs and web/scripts/embed-spec.mjs, so adding a spec there
 * is the only place that needs to change.
 *
 * No external references to strip here (unlike build/inline-docs.mjs) — it's
 * two links and enough CSS not to look bare, so it doesn't reuse that script.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..');

const redoclyConfig = parse(readFileSync(resolve(repo, 'redocly.yaml'), 'utf8'));
const slugs = Object.keys(redoclyConfig.apis ?? {});

function titleCase(slug) {
  return slug.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');
}

const items = slugs
  .map((slug) => `      <li><a href="./${slug}.html">${titleCase(slug)}</a></li>`)
  .join('\n');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>A2M8 API Contracts</title>
<style>
  body { font: 16px/1.5 -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; max-width: 40rem; margin: 4rem auto; padding: 0 1.5rem; color: #1a1a1a; }
  h1 { font-size: 1.4rem; }
  ul { padding-left: 1.2rem; }
  a { color: #4f46e5; text-decoration: none; }
  a:hover { text-decoration: underline; }
</style>
</head>
<body>
  <h1>A2M8 API contracts</h1>
  <p>Offline, no-network reference for each spec — generated by <code>npm run docs</code>.</p>
  <ul>
${items}
  </ul>
</body>
</html>
`;

writeFileSync(resolve(repo, 'docs', 'index.html'), html);
console.log(`write-docs-index: docs/index.html -> ${slugs.length} spec(s)`);
